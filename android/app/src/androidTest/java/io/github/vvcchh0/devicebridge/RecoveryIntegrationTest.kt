package io.github.vvcchh0.devicebridge

import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import io.github.vvcchh0.devicebridge.data.OperationStore
import io.github.vvcchh0.devicebridge.data.ProfileStore
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class RecoveryIntegrationTest {
    @Test fun encryptedRecordsRejectTamperingAndDoNotContainPlaintext() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val store = OperationStore(context)
        val id = "b".repeat(64)
        store.clear(id)
        store.save(id, listOf(PendingOperation("encrypted-test", "synthetic-session", "合成敏感记录", "unknown")))
        val file = java.io.File(context.noBackupFilesDir, "devicebridge-v1/operations-$id.v1.enc")
        val bytes = file.readBytes()
        assertFalse(bytes.toString(Charsets.UTF_8).contains("合成敏感记录"))
        bytes[bytes.lastIndex] = (bytes.last().toInt() xor 1).toByte()
        file.writeBytes(bytes)
        try { store.load(id); fail("tampered record accepted") }
        catch (_: io.github.vvcchh0.devicebridge.data.OperationStoreException) { }
        assertTrue(file.exists())
        store.clear(id)
    }

    @Test fun interruptedSendingIsRecoveredWithoutLosingIdentity() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val store = OperationStore(context)
        val profile = "a".repeat(64)
        store.clear(profile)
        val attempt = PendingOperation("same-operation", "synthetic-session", "合成消息", "sending")
        store.save(profile, listOf(attempt))
        val recovered = OperationStore(context).load(profile).single()
        assertEquals("unknown", recovered.state)
        assertEquals(attempt.id, recovered.id)
        assertEquals(attempt.text, recovered.text)
        store.clear(profile)
    }

    @Test fun liveTlsLostReplyReconcilesOriginalOperation() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val assets = instrumentation.context.assets
        assumeTrue("live fixture explicitly generated by host", assets.list("")?.contains("bridge-test.json") == true)
        val fixture = JSONObject(assets.open("bridge-test.json").bufferedReader().use { it.readText() })
        val context = instrumentation.targetContext
        val repository = BridgeRepository(context)
        val profileJson = fixture.getJSONObject("profile")
        val profile = repository.profiles.importJson(profileJson.toString())
        assertEquals(profile.id, ProfileStore(context).load()?.id)
        val sessions = repository.catalog(profile)
        val session = sessions.single { it.label == "codex" }
        assertTrue(session.canSend)
        assertFalse(session.freeText)
        assertTrue(repository.history(profile, session.label).messages.isNotEmpty())
        val id = fixture.getString("operationId")
        val first = repository.send(profile, session, fixture.getString("message"), id)
        assertEquals("unknown", first.state) // Dedicated host intentionally drops only this ACK.
        val restored = BridgeRepository(context)
        assertEquals(id, restored.outbox.load(profile.id).single { it.id == id }.id)
        var resolved = restored.reconcile(profile, id)
        assertEquals("completed", resolved.state)
        assertEquals("completed", restored.send(profile, session, fixture.getString("message"), id).state)
        val deadline = System.currentTimeMillis() + 60000
        while (resolved.turnStatus !in setOf("completed", "failed", "interrupted") && System.currentTimeMillis() < deadline) {
            Thread.sleep(2500)
            resolved = restored.reconcile(profile, id)
        }
        assertEquals("completed", resolved.turnStatus)
        assertTrue(restored.history(profile, session.label).messages.any { it.role == "assistant" && it.text.trim() == "DEVICE_BRIDGE_ACK_V1" })
        val badPin = JSONObject(profileJson.toString()).put("serverCertificateSha256", "0".repeat(64))
        try { repository.profiles.importJson(badPin.toString()); fail("wrong certificate pin accepted") }
        catch (_: io.github.vvcchh0.devicebridge.data.ProfileStoreException) { }
        assertEquals(profile.id, repository.profiles.load()?.id)
    }
}
